document.addEventListener("DOMContentLoaded", () => {
  const select = document.getElementById("languageSelect");

  function applyLanguage(language) {
    const lang = translations[language] ? language : "en";
    document.documentElement.lang = lang;

    document.querySelectorAll("[data-i18n]").forEach((element) => {
      const key = element.dataset.i18n;
      if (translations[lang][key] !== undefined) {
        element.textContent = translations[lang][key];
      }
    });

    try {
      localStorage.setItem("farmToHomeLanguage", lang);
    } catch (error) {
      // Language works for this page even if storage is unavailable.
    }
  }

  let savedLanguage = "en";

  try {
    savedLanguage = localStorage.getItem("farmToHomeLanguage") || "en";
  } catch (error) {
    // Use English by default.
  }

  if (select) {
    select.value = translations[savedLanguage] ? savedLanguage : "en";
    select.addEventListener("change", () => applyLanguage(select.value));
  }

  applyLanguage(savedLanguage);
});